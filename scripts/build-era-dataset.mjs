function recordId(record) {
  return createHash('sha256').update(JSON.stringify(record), 'utf8').digest('hex');
}

const records = [];
const manifest = [];
for (const group of groups) {
  for (const [startYear, endYear, title, summary, sourceKey] of group.items) {
    for (const aspect of ASPECTS) {
      const record = {
        start_year: startYear,
        end_year: endYear,
        category: group.category,
        title: `${title}：${aspect}`,
        summary: `${summary} 从${aspect}的角度看，这一背景常常通过具体物品、场景和家庭故事被记住。`,
      };
      const id = recordId(record);
      records.push(record);
      manifest.push({
        record_id: id,
        source_url: SOURCES[sourceKey].url,
        source_title: SOURCES[sourceKey].title,
        source_level: SOURCES[sourceKey].level,
        status: 'curated-derived',
      });
    }
  }
}

if (records.length !== 1_800) throw new Error(`Expected 1800 records, got ${records.length}.`);
await mkdir(path.dirname(OUTPUT), { recursive: true });
await writeFile(OUTPUT, records.map((record) => JSON.stringify(record)).join('\n') + '\n', 'utf8');
await writeFile(MANIFEST, manifest.map((item) => JSON.stringify(item)).join('\n') + '\n', 'utf8');
